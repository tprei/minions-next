import { isAbsolute } from "node:path";
import process from "node:process";

import {
  createCredentialVault,
  createGitHubAppAuth,
  createPullRequestManager,
  createPushManager,
  resolveEngineBotIdentity,
} from "@minions/adapters";

// PR 32 focused synthetic: push a commit to a test branch under an expected-head
// lease, open one PR for that branch, observe its review state and checks, then
// prove an idempotent re-push is a no-op. Exercises the real push + PR managers
// against a maintained GitHub App installation on a dedicated test repository.
//
// This is the DEFERRED capability gate for PR 32 — it requires credentials in the
// OS credential store plus a commit that already exists in the test repository.
// Run on the disposable host:
//
//   OMP_GITHUB_HOST_ID=<hostId> \
//   OMP_GITHUB_STORE_DIR=<abs-dir> \
//   OMP_GITHUB_APP_ID=<appId> \
//   OMP_GITHUB_PRIVATE_KEY_NAME=<vault-entry> \
//   OMP_GITHUB_TEST_REPO=<owner>/<repo> \
//   OMP_GITHUB_TEST_BRANCH=<branch> \
//   OMP_GITHUB_TEST_SHA=<40-hex-commit-sha> \
//   pnpm synthetic:github-pr
//
// The runner exits non-zero if the push is rejected (drift/lease), if more than
// one PR exists for the branch, or if review/check observation fails.

await main();

async function main() {
  try {
    await runSynthetic(loadConfiguration());
  } catch (error) {
    process.stderr.write(`${formatError(error)}\n`);
    process.exitCode = 1;
  }
}

function loadConfiguration() {
  const hostId = requiredEnvironment("OMP_GITHUB_HOST_ID");
  const storeDirectory = requiredAbsolutePath("OMP_GITHUB_STORE_DIR");
  const appId = Number.parseInt(requiredEnvironment("OMP_GITHUB_APP_ID"), 10);
  if (!Number.isFinite(appId) || appId <= 0) {
    throw new Error("OMP_GITHUB_APP_ID must be a positive integer (the GitHub App id).");
  }
  const privateKeyCredentialName = requiredEnvironment("OMP_GITHUB_PRIVATE_KEY_NAME");
  const testRepository = requiredEnvironment("OMP_GITHUB_TEST_REPO");
  if (!testRepository.includes("/")) {
    throw new Error("OMP_GITHUB_TEST_REPO must be 'owner/name'.");
  }
  const testBranch = requiredEnvironment("OMP_GITHUB_TEST_BRANCH");
  const testSha = requiredEnvironment("OMP_GITHUB_TEST_SHA");
  if (!/^[0-9a-f]{40}$/u.test(testSha)) {
    throw new Error("OMP_GITHUB_TEST_SHA must be a 40-hex git commit SHA that exists in the repo.");
  }
  const vault = createCredentialVault(hostId, {
    storeDirectory,
    systemdCredsPath: "/usr/bin/systemd-creds",
    systemdCredsKeyMode: "host",
  });
  const probe = vault.probe();
  if (!probe.available) {
    throw new Error(
      `credential vault backend unavailable on this host: ${probe.detail ?? probe.backend}`,
    );
  }
  return Object.freeze({
    appId,
    privateKeyCredentialName,
    testRepository,
    testBranch,
    testSha,
    vault,
  });
}

async function runSynthetic(configuration) {
  const auth = createGitHubAppAuth({
    vault: configuration.vault,
    privateKeyCredentialName: configuration.privateKeyCredentialName,
    appId: configuration.appId,
  });

  // 1. Resolve the engine bot identity (GIT-11): the engine's own reviews are
  //    not eligible for independent human review.
  const identity = await resolveEngineBotIdentity(auth);
  emit({ step: "resolve_engine_bot_identity", login: identity.botLogin, appId: identity.appId });

  const repositoryFullName = configuration.testRepository;
  const bookmark = configuration.testBranch;

  // The synthetic supplies a commit that already exists in the repo, so the
  // local `jj git export` is a no-op: exportCommit returns the supplied SHA.
  const push = createPushManager({
    auth,
    workingCopy: {
      async exportCommit() {
        return { commitSha: configuration.testSha };
      },
    },
  });

  // 2. Push the commit under an expected-head lease (new branch → undefined).
  const pushReceipt = await push.push({
    repositoryFullName,
    bookmark,
    jjChangeId: "synthetic".padEnd(64, "0"),
    expectedRemoteHeadSha: undefined,
  });
  emit({ step: "push", action: pushReceipt.action, sha: pushReceipt.remoteHeadSha });

  // 3. Open (or update) exactly one PR for the branch — GIT-03.
  const pr = createPullRequestManager({ auth, botIdentity: identity });
  const prReceipt = await pr.createOrUpdatePR({
    repositoryFullName,
    bookmark,
    baseBranch: "main",
    title: `[synthetic] PR 32 push+review observation on ${bookmark}`,
    body: "Generated by synthetic:github-pr.",
    draft: false,
  });
  emit({ step: "create_or_update_pr", action: prReceipt.action, number: prReceipt.prNumber });

  // 4. Observe review state — fresh human vs stale vs bot vs pending (GIT-11).
  const review = await pr.observeReviewState(repositoryFullName, prReceipt.prNumber);
  emit({
    step: "observe_review_state",
    state: review.state,
    fresh: review.freshApprovals.length,
    stale: review.staleApprovals.length,
    bot: review.botApprovals.length,
  });

  // 5. Observe checks — pass/fail/pending/missing.
  const checks = await pr.observeChecks(repositoryFullName, prReceipt.prNumber);
  emit({
    step: "observe_checks",
    state: checks.state,
    total: checks.totalCheckRuns,
    failing: checks.failingNames,
    pending: checks.pendingNames,
  });

  // 6. Idempotent re-push: the remote head already equals the commit → no-op.
  const rePush = await push.push({
    repositoryFullName,
    bookmark,
    jjChangeId: "synthetic".padEnd(64, "0"),
    expectedRemoteHeadSha: pushReceipt.remoteHeadSha,
  });
  if (rePush.action !== "noop") {
    throw new Error(`expected idempotent re-push to be a no-op, got '${rePush.action}'`);
  }
  emit({ step: "idempotent_repush", action: rePush.action });

  emit({ step: "synthetic_complete", repository: repositoryFullName, bookmark });
}

function emit(record) {
  process.stdout.write(`${JSON.stringify(record)}\n`);
}

function requiredEnvironment(name) {
  const value = process.env[name];
  if (typeof value !== "string" || value.length === 0) {
    throw new Error(
      `${name} must be set. Remediation: configure the maintained GitHub App + test repository on the disposable host.`,
    );
  }
  return value;
}

function requiredAbsolutePath(name) {
  const value = requiredEnvironment(name);
  if (!isAbsolute(value)) {
    throw new Error(`${name} must be an absolute path.`);
  }
  return value;
}

function formatError(error) {
  if (error instanceof Error) return error.message;
  return String(error);
}
